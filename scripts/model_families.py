def discovery_links(discoveries):
    return {fid: [d['id'] for d in discoveries
                  if re.search(pattern, ' '.join([d.get('ai_technology', ''), d.get('title', '')]), re.I)]
            for fid, _, _, pattern in FAMILIES}
